const choice = (
  id: string,
  skillId: string,
  difficulty: Difficulty,
  prompt: string,
  options: string[],
  correct: number,
  explanation: string,
  hint?: string,
  theory?: string,
): ChoiceActivity => ({
  type: "choice",
  id,
  skillId,
  difficulty,
  prompt,
  options,
  correct,
  explanation,
  hint,
  theory,
});

const input = (
  id: string,
  skillId: string,
  difficulty: Difficulty,
  prompt: string,
  answers: string[],
  explanation: string,
  options: { hint?: string; placeholder?: string; suffix?: string } = {},
  theory?: string,
): InputActivity => ({
  type: "input",
  id,
  skillId,
  difficulty,
  prompt,
  answers,
  explanation,
  theory,
  ...options,
});

const match = (
  id: string,
  skillId: string,
  difficulty: Difficulty,
  prompt: string,
  pairs: [string, string][],
  explanation: string,
  theory?: string,
): MatchActivity => ({
  type: "match",
  id,
  skillId,
  difficulty,
  prompt,
  explanation,
  theory,
  pairs: pairs.map(([left, right], index) => ({
    id: `${id}-p${index + 1}`,
    left,
    right,
  })),
});

