/* --------------------------------------------------------------------------
   Pequeños constructores para que el contenido se lea como una ficha, no
   como una pared de objetos.
   -------------------------------------------------------------------------- */

const choice = (
  id: string,
  skillId: string,
  difficulty: Difficulty,
  prompt: string,
  options: string[],
  correct: number,
  explanation: string,
  hint?: string,
): ChoiceActivity => ({
  type: "choice",
  id,
  skillId,
  difficulty,
  prompt,
  options,
  correct,
  explanation,
  hint,
});

const input = (
  id: string,
  skillId: string,
  difficulty: Difficulty,
  prompt: string,
  answers: string[],
  explanation: string,
  options: { hint?: string; placeholder?: string; suffix?: string } = {},
): InputActivity => ({
  type: "input",
  id,
  skillId,
  difficulty,
  prompt,
  answers,
  explanation,
  ...options,
});

const match = (
  id: string,
  skillId: string,
  difficulty: Difficulty,
  prompt: string,
  pairs: [string, string][],
  explanation: string,
): MatchActivity => ({
  type: "match",
  id,
  skillId,
  difficulty,
  prompt,
  explanation,
  pairs: pairs.map(([left, right], index) => ({
    id: `${id}-p${index + 1}`,
    left,
    right,
  })),
});

